def ask_api(question):
    started = time.perf_counter()
    r = requests.post(API_URL, json={"question": question, "top_k": TOP_K}, timeout=TIMEOUT)
    latency = round(time.perf_counter() - started, 3)
    r.raise_for_status()
    return r.json(), latency

def save_results(results):
    Path(OUTPUT_JSON).write_text(json.dumps(results, ensure_ascii=False, indent=2), encoding="utf-8")
    fields = ["id","category","question","reference_answer","answer","sources","retrieved_contexts","top_k","best_semantic_score","retrieval","latency_seconds","status","error"]
    with open(OUTPUT_CSV, "w", newline="", encoding="utf-8-sig") as f:
        w = csv.DictWriter(f, fieldnames=fields)
        w.writeheader()
        for row in results:
            out = dict(row)
            out["sources"] = " | ".join(out.get("sources", []))
            out["retrieved_contexts"] = " ||| ".join(out.get("retrieved_contexts", []))
            w.writerow({k: out.get(k, "") for k in fields})

def main():
    try:
        health_url = API_URL.rsplit("/", 1)[0] + "/health"
        h = requests.get(health_url, timeout=10)
        h.raise_for_status()
        print("API health:", h.json())
    except Exception as e:
        print("Δεν βρέθηκε ενεργό API. Τρέξε πρώτα: python rag_api.py")
        print("Σφάλμα:", e)
        return

    results = []
    for i, (qid, category, question, reference) in enumerate(QUESTIONS, 1):
        print(f"[{i:02d}/20] {qid}: {question}")
        row = {
            "id": qid, "category": category, "question": question,
            "reference_answer": reference, "answer": "", "sources": [], "retrieved_contexts": [],
            "top_k": TOP_K, "best_semantic_score": None, "retrieval": "",
            "latency_seconds": None, "status": "ok", "error": ""
        }
        try:
            data, latency = ask_api(question)
            row["answer"] = data.get("answer", "")
            row["sources"] = data.get("sources", [])
            row["retrieved_contexts"] = data.get("retrieved_contexts", [])
            row["top_k"] = data.get("top_k", TOP_K)
            row["best_semantic_score"] = data.get("best_semantic_score")
            row["retrieval"] = data.get("retrieval", "")
            row["latency_seconds"] = latency
            print(f"  ✓ {latency}s | {row['retrieval']} | sources={len(row['sources'])}")
        except Exception as e:
            row["status"] = "error"
            row["error"] = str(e)
            print("  ✗", e)
        results.append(row)
        save_results(results)

    print("Ολοκληρώθηκε.")
    print("Αρχεία:", OUTPUT_JSON, "και", OUTPUT_CSV)

if __name__ == "__main__":
    main()
